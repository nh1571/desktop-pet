"""Pixel art sprite data. Each sprite is a 16x16 grid of palette indices.

Sprites are defined as lists of 16-character strings for readability.
Use sprite_from_ascii() to convert to 2D index grids.
"""

from config import CHAR_MAP


def sprite_from_ascii(*rows: str) -> list:
    """Convert ASCII art rows to a 16x16 pixel grid (list of lists of palette indices).

    Each row is padded/truncated to exactly 16 characters.
    Characters map to palette indices via CHAR_MAP.
    Spaces are transparent (index 0).
    """
    grid = []
    for row in rows:
        row = row.ljust(16)[:16]
        grid.append([CHAR_MAP.get(c, 0) for c in row])
    assert len(grid) == 16, f"Sprite must be 16 rows, got {len(grid)}"
    return grid


